export async function runTier03Checks({ evaluate, until, check, clickText, viewport, layout, key }) {
  const body = text => `document.body.textContent.includes(${JSON.stringify(text)})`;
  const send = `Array.from(document.querySelectorAll('button')).find(e=>e.textContent==='Send weather by SMS')`;
  const remount = async (profile = 'live', outcome = 'simulated') => {
    await evaluate(`tier03.profile=${JSON.stringify(profile)};tier03.outcome=${JSON.stringify(outcome)};fixture.remount()`);
    await until(`${body('Messaging profile loaded')} || ${body('live SMS is unavailable')}`);
  };
  const weather = async mode => { await evaluate(`tier03.weather=${JSON.stringify(mode)}`); await clickText('button', 'Refresh advisory'); };
  const openStatus = async () => evaluate(`Array.from(document.querySelectorAll('summary')).find(e=>e.textContent==='Consent, routine schedule and delivery').closest('details').open=true`);
  await until(`${body('Messaging profile loaded')} && !${send}.disabled`);
  await openStatus();
  check('saved schedule and missing official warning coverage are explicit', await evaluate(`${body('Official warning feed')} && ${body('Monday, Friday')} && ${body('Safety decision and rule version')}`));
  check('consent does not fabricate verification, eligibility or delivery history', await evaluate(`${body('Granted in the saved profile')} && ${body('callback-backed')} && ${body('Live messaging eligibility')} && !${body('Verified by the service')}`));
  check('routine weekdays, any-day alerts and sponsor/cost limitations remain distinct', await evaluate(`${body('may occur any day')} && ${body('not include sponsor messages')} && ${body('No confirmed segment count')}`));
  await layout('TIER-03 advisory desktop / expanded status');
  await evaluate(`tier03.holdSms=true`);
  await clickText('button', 'Send weather by SMS');
  await until('Boolean(tier03.releaseSms)');
  check('pending SMS state is announced and repeated clicks cannot submit twice', await evaluate(`(()=>{const e=Array.from(document.querySelectorAll('button')).find(e=>e.textContent==='Sending request…');e.click();return e.disabled && tier03.smsCalls===1 && Boolean(e.closest('section').querySelector('[role="status"]'))})()`));
  await evaluate('tier03.releaseSms()');
  await until(body('SMS preview simulated'));
  check('simulation never claims a message was sent or enables duplicate submission', await evaluate(`${body('No message was sent')} && ${send}.disabled`));
  await remount('live', 'accepted');
  await clickText('button', 'Send weather by SMS');
  await until(body('Accepted for SMS dispatch'));
  check('accepted dispatch stays distinct from receipt', await evaluate(`${body('Delivery has not been confirmed')} && ${send}.disabled`));
  await remount('live', 'unknown');
  await clickText('button', 'Send weather by SMS');
  await until(body('Dispatch and delivery are unknown'));
  check('unrecognized response cannot become queued or delivered success', await evaluate(body('Unrecognized response')));
  await remount('live', 'failed');
  await clickText('button', 'Send weather by SMS');
  await until(body('another request could duplicate'));
  check('retryable error preserves uncertainty before explicit retry', await evaluate(`tier03.smsCalls===4 && !Array.from(document.querySelectorAll('button')).find(e=>e.textContent==='Try again').disabled`));
  await evaluate(`tier03.outcome='simulated'`);
  await clickText('button', 'Try again');
  await until(body('SMS preview simulated'));
  check('explicit retry uses only mocked transport', await evaluate('tier03.smsCalls===5'));
  await remount('live', 'denied');
  await clickText('button', 'Send weather by SMS');
  await until(body('Request denied'));
  check('denied send is visible without delivery success', await evaluate(`${send}.disabled && !${body('Accepted for SMS dispatch')}`));
  await remount('demo');
  check('demo account cannot request live SMS and has explicit unverified status', await evaluate(`${send}.disabled && ${body('contact unverified')}`));
  await evaluate(`tier03.profile='denied'`);
  await clickText('button', 'Refresh messaging status');
  await until(body('Messaging status access denied'));
  check('denied profile hides prior consent and blocks send', await evaluate(`${send}.disabled && !${body('Granted in the saved profile')}`));
  await evaluate(`tier03.profile='failed'`);
  await clickText('button', 'Refresh messaging status');
  await until(body('Messaging status unavailable'));
  check('profile outage is recoverable with no eligibility invention', await evaluate(`${send}.disabled && ${body('cannot be confirmed')}`));
  await evaluate(`tier03.profile='paused'`);
  await clickText('button', 'Refresh messaging status');
  await until(body('Routine schedule paused'));
  check('zero routine days do not hide any-day critical alerts', await evaluate(body('may occur any day')));
  await evaluate(`tier03.profile='mismatch'`);
  await clickText('button', 'Refresh messaging status');
  await until(body('Messaging status unavailable'));
  check('cross-account profile response is rejected', await evaluate(`${send}.disabled`));
  await evaluate(`tier03.profile='live';tier03.holdProfile=true`);
  await clickText('button', 'Refresh messaging status');
  await until('Boolean(tier03.releaseProfile)');
  check('profile refresh has a loading state and disables sending', await evaluate(`${body('Loading messaging status')} && ${send}.disabled`));
  await evaluate('fixture.changeAccount()');
  await until(body('Messaging profile loaded'));
  await evaluate('tier03.releaseProfile()');
  check('late previous-account response cannot replace current status', await evaluate(body('Messaging profile loaded')));
  await weather('warning');
  await until(body('Test-only regional restriction'));
  check('warning survives malformed wind and unavailable waves', await evaluate(`${body('Parola hold active')} && ${body('Recorded storm signal: ')} && ${send}.disabled`));
  await weather('failed');
  await until(body('Refresh failed; last available record only'));
  check('known warning remains visible through total refresh outage', await evaluate(`${body('Test-only regional restriction')} && ${body('Parola hold active')}`));
  await weather('missing');
  await until(body('Missing, stale or undated check'));
  check('partial refresh retains warning without calling it current', await evaluate(`${body('current status is unconfirmed')} && ${body('Missing, stale or undated check')}`));
  await weather('expired');
  await until(body('Advisory incomplete'));
  check('expired essential evidence prevents clear status and SMS request', await evaluate(`${send}.disabled && ${body('expired')}`));
  await evaluate(`tier03.weather='empty';fixture.remount()`);
  await until(body('Advisory incomplete'));
  check('empty response is unavailable rather than zero or safe', await evaluate(`${body('unavailable / unavailable')} && !${body('No Parola hold detected')}`));
  await evaluate(`fixture.route('/dashboard')`);
  await until(body('Fishing guidance withheld'));
  await until(`Boolean(document.querySelector('#fishing-areas ol button'))`);
  check('map and list keep records explicitly separate from fishing guidance', await evaluate(`${body('Map markers are reference records')} && ${body('essential safety checks are incomplete')}`));
  await evaluate(`document.querySelector('#fishing-areas ol button').click()`);
  await until(body('Prediction provenance and validity'));
  check('unknown safety hides actionable model estimate but keeps reference details', await evaluate(`!${body('80%')} && ${body('14.0500')}`));
  await evaluate(`fixture.route('/alerts')`);
  await until(body('Warnings and coverage'));
  await openStatus();
  for (const width of [768, 390, 320]) { await viewport(width); await layout(`TIER-03 advisory ${width}px / expanded status`); }
  await evaluate(`document.documentElement.style.fontSize='32px'`);
  await layout('TIER-03 320px / enlarged text');
  await evaluate(`document.documentElement.style.fontSize=''`);
  await evaluate(`Array.from(document.querySelectorAll('summary')).find(e=>e.textContent==='Consent, routine schedule and delivery').focus()`);
  await key('Enter');
  check('keyboard toggles the named disclosure with visible focus', await evaluate(`document.activeElement.tagName==='SUMMARY' && !document.activeElement.parentElement.open && getComputedStyle(document.activeElement).outlineStyle!=='none'`));
  check('only expected mocked endpoint paths were handled', await evaluate(`tier03.requests.every(path=>['/api/dashboard/weather','/api/users/profile','/api/sms/send','/api/advisories/nearest'].includes(path))`));
}
